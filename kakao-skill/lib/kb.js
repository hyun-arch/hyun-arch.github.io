/** 키워드가 겹치는 수로 고른다. 애매하면 null 을 돌려 모델에게 넘긴다. */
export function match(utterance) {
  const t = String(utterance || '').toLowerCase().replace(/\s+/g, '');
  let best = null, score = 0;
  for (const e of KB) {
    const s = e.kw.reduce((n, k) => n + (t.includes(k.toLowerCase().replace(/\s+/g, '')) ? k.length : 0), 0);
    if (s > score) { score = s; best = e; }
  }
  return score >= 2 ? best : null;
}


export function stats() {
  const submitted = people.filter((p) => p.gene !== 'empty');
  const byGene = {};
  genes.forEach((g) => { byGene[g.id] = 0; });
  people.forEach((p) => { byGene[p.gene] = (byGene[p.gene] || 0) + 1; });
  const bothN = people.filter((p) => p.both).length;
  return {
    total: people.length,          // 명단 항목 수 (1기 + 2기)
    uniq: people.length - bothN / 2, // 실제 사람 수 (양 기수 참여자는 1명으로)
    gen1: people.filter((p) => p.gen === 1).length,
    gen2: people.filter((p) => p.gen === 2).length,
    both: bothN / 2,               // 1·2기 모두 참여한 사람 수
    bothRows: bothN,
    submitted: submitted.length,
    empty: people.length - submitted.length,
    geneCount: genes.filter((g) => g.id !== 'empty').length,
    byGene,
    top: genes
      .filter((g) => g.id !== 'empty')
      .map((g) => ({ ...g, n: byGene[g.id] || 0 }))
      .sort((a, b) => b.n - a.n),
  };
}

